"""Typed aggregate persistence boundary for the redesign use cases."""

from datetime import datetime
from typing import Protocol

from attendance_lab.domain.redesign import (
    AcademicGroup,
    AcademicYear,
    Evidence,
    ImportPlan,
    ManualBatch,
    Profile,
    RegistrationSession,
    ScheduledBlock,
    Specialty,
    StudentContext,
    TeachingRoster,
)


class RedesignStore(Protocol):
    def rd_revision(self) -> str: ...
    def rd_years(self) -> list[AcademicYear]: ...
    def rd_save_year(self, start_year: int) -> AcademicYear: ...
    def rd_specialties(self) -> list[Specialty]: ...
    def rd_profiles(self) -> list[Profile]: ...
    def rd_resolve_specialty(self, key: str) -> int | None: ...
    def rd_resolve_profile(self, specialty_id: int, key: str) -> int | None: ...
    def rd_save_specialty(self, name: str, entity_id: int = 0) -> Specialty: ...
    def rd_save_profile(self, specialty_id: int, name: str, entity_id: int = 0) -> Profile: ...
    def rd_specialty_alias(self, specialty_id: int, name: str) -> None: ...
    def rd_profile_alias(self, profile_id: int, name: str) -> None: ...
    def rd_groups(self) -> list[AcademicGroup]: ...
    def rd_save_group(self, value: AcademicGroup) -> AcademicGroup: ...
    def rd_contexts(self, year_id: int | None = None) -> list[StudentContext]: ...
    def rd_save_book(self, student_id: str, number: str) -> None: ...
    def rd_membership(
        self, student_id: str, year_id: int, group_id: int, profile_id: int | None
    ) -> None: ...
    def rd_import_batch(self, year_id: int, plan: ImportPlan, student_ids: list[str]) -> None: ...
    def rd_discipline_groups(self, discipline_id: int, year_id: int) -> set[int]: ...
    def rd_set_discipline_groups(
        self, discipline_id: int, year_id: int, groups: set[int]
    ) -> None: ...
    def rd_rosters(self) -> list[TeachingRoster]: ...
    def rd_save_roster(self, value: TeachingRoster) -> TeachingRoster: ...
    def rd_blocks(self) -> list[ScheduledBlock]: ...
    def rd_save_block(self, value: ScheduledBlock) -> ScheduledBlock: ...
    def rd_context_snapshot(self, pair_id: int) -> list[StudentContext]: ...
    def rd_save_snapshot(
        self, pair_id: int, contexts: list[StudentContext], reason: str = ""
    ) -> None: ...
    def rd_sessions(self) -> list[RegistrationSession]: ...
    def rd_save_session(
        self, value: RegistrationSession, *, audit: bool = False
    ) -> RegistrationSession: ...
    def rd_add_card_evidence(self, session_id: int, uid: str, at: datetime) -> None: ...
    def rd_pair_evidence(self, pair_id: int) -> list[Evidence]: ...
    def rd_batches(self) -> list[ManualBatch]: ...
    def rd_save_batch(
        self, value: ManualBatch, student_ids: tuple[str, ...] = ()
    ) -> ManualBatch: ...
